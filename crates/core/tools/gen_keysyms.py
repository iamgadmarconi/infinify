"""Generate src/platform/input/keyboard/keysyms.rs.

Not part of the build: the generated file is committed. This script exists so
the table can be regenerated and audited.

Inputs (crates.io sources, read as text, never compiled):

  --xkeysym    xkeysym-0.2.1/src/automatically_generated.rs
               Source of the name -> value data. xkeysym generates its `key`
               module from the X.Org keysym headers and keeps each C macro name
               as a `#[doc(alias = "...")]`.
  --xkbcommon  xkbcommon-0.9.0/src/xkb/keysyms.rs
               The `KEY_*` constants upstream DriftWM compiles against (through
               smithay). Used as a cross-check, and as the source of the one
               name xkeysym's generator drops (`hpYdiaeresis`).
  --xkbcommon-rs (optional) xkbcommon-rs-0.1.2/src/keysyms_generated_phf.rs
               A Rust port of libxkbcommon 1.7.0's name table. Cross-check only.

Name derivation is libxkbcommon's own header rule (`scripts/makeheader`):
`#define (\\w*)XK_<rest>` becomes `XKB_KEY_\\1<rest>`, so `XK_Return` is
`Return`, `XF86XK_AudioMute` is `XF86AudioMute`, `SunXK_F36` is `SunF36`,
`DXK_ring_accent` is `Dring_accent`, `hpXK_mute_acute` is `hpmute_acute` and
`osfXK_Copy` is `osfCopy`.

The table is emitted in libxkbcommon's `name_to_keysym` order: by ASCII
case-folded name, then by name, so that among names differing only in case the
upper-case spelling comes first and the lower-case one last.

The output is passed through `rustfmt --edition 2024` (it wraps the few table
rows that are too wide), so `cargo fmt -- --check` accepts the committed file.
"""

import argparse
import re
import subprocess
import sys


def parse_xkeysym(path):
    text = open(path, encoding="utf-8").read()
    key_mod = text.split("pub mod key {", 1)[1].split("\n}\n", 1)[0]
    found = re.findall(
        r'#\[doc\(alias = "([^"]+)"\)\]\s*pub const (\w+): RawKeysym = (0x[0-9a-fA-F]+);',
        key_mod,
    )
    total = len(re.findall(r"pub const \w+: RawKeysym = ", key_mod))
    if total != len(found):
        sys.exit(f"xkeysym: {total} constants but {len(found)} carry a doc alias")
    table = {}
    for alias, _ident, value in found:
        m = re.fullmatch(r"(\w*?)XK_(.+)", alias)
        if not m:
            sys.exit(f"xkeysym: unexpected alias {alias!r}")
        name = m.group(1) + m.group(2)
        value = int(value, 16)
        if table.setdefault(name, value) != value:
            sys.exit(f"xkeysym: {name} has two values")
    return table


def parse_xkbcommon(path):
    text = open(path, encoding="utf-8").read()
    found = re.findall(r"^pub const KEY_(\w+): u32 = (0x[0-9a-fA-F_]+);", text, re.M)
    table = {}
    for name, value in found:
        value = int(value.replace("_", ""), 16)
        if table.setdefault(name, value) != value:
            sys.exit(f"xkbcommon: {name} has two values")
    return table


def parse_xkbcommon_rs(path, xkeysym_path):
    text = open(xkeysym_path, encoding="utf-8").read()
    key_mod = text.split("pub mod key {", 1)[1].split("\n}\n", 1)[0]
    idents = {
        ident: int(value, 16)
        for ident, value in re.findall(
            r"pub const (\w+): RawKeysym = (0x[0-9a-fA-F]+);", key_mod
        )
    }
    body = open(path, encoding="utf-8").read()
    body = body.split("phf_ordered_map! {", 1)[1].split("};", 1)[0]
    pairs = re.findall(r'"([^"]+)" => Keysym::(\w+),', body)
    return [(name, idents[ident]) for name, ident in pairs]


def fold(name):
    # ASCII-only case folding, as libxkbcommon's istrcmp().
    return "".join(chr(ord(c) + 32) if "A" <= c <= "Z" else c for c in name)


HEADER = """\
// SPDX-License-Identifier: GPL-3.0-or-later
// GENERATED by tools/gen_keysyms.py -- do not edit by hand.
//
// Stand-in for `smithay::input::keyboard::keysyms` as imported by
// malbiruk/driftwm src/config at 352333a8fa1b22171492d4b71a54102045c9a19d.
// Upstream's module is `xkbcommon::xkb::keysyms` (crate xkbcommon 0.9.0): the
// `KEY_<name>` constants of libxkbcommon's `xkbcommon-keysyms.h`.
//
// Data: keysym names and values from xkeysym 0.2.1
// `src/automatically_generated.rs` (MIT OR Apache-2.0 OR Zlib, generated from
// the X.Org xorgproto 2024.1 keysym headers), renamed with libxkbcommon's
// header rule, plus `hpYdiaeresis` from xkbcommon 0.9.0 `src/xkb/keysyms.rs`
// (MIT; X.Org keysym headers). See PORT.md for hashes and cross-checks.
//
// Unlike upstream's module this one also carries the name table that
// libxkbcommon keeps in C (`ks_tables.h`), which `xkb::keysym_from_name` needs.

#![allow(non_upper_case_globals)]

"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--xkeysym", required=True)
    ap.add_argument("--xkbcommon", required=True)
    ap.add_argument("--xkbcommon-rs")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    table = parse_xkeysym(args.xkeysym)
    print(f"xkeysym 0.2.1: {len(table)} names")

    xkb = parse_xkbcommon(args.xkbcommon)
    print(f"xkbcommon 0.9.0: {len(xkb)} names")
    added = []
    for name, value in xkb.items():
        if name not in table:
            table[name] = value
            added.append(name)
        elif table[name] != value:
            sys.exit(f"value mismatch for {name}: {table[name]:#x} vs {value:#x}")
    print(f"names taken from xkbcommon 0.9.0 only: {added}")
    print(f"names not in xkbcommon 0.9.0: {len(set(table) - set(xkb))}")

    if args.xkbcommon_rs:
        rs = parse_xkbcommon_rs(args.xkbcommon_rs, args.xkeysym)
        rs_map = dict(rs)
        only_here = sorted(set(table) - set(rs_map))
        only_rs = sorted(set(rs_map) - set(table))
        diff = sorted(n for n in set(table) & set(rs_map) if table[n] != rs_map[n])
        print(
            f"xkbcommon-rs 0.1.2: {len(rs)} names; only here {only_here}; "
            f"only there {only_rs}; value mismatches {diff}"
        )
        if only_rs or diff:
            sys.exit("xkbcommon-rs cross-check failed")

    for name in table:
        if not re.fullmatch(r"[A-Za-z0-9_]+", name):
            sys.exit(f"non-identifier keysym name {name!r}")

    ordered = sorted(table, key=lambda n: (fold(n), n))

    groups = {}
    for name in ordered:
        groups.setdefault(fold(name), []).append(name)
    dup = [g for g in groups.values() if len(g) > 1]
    print(f"total: {len(ordered)} names, {len(set(table.values()))} distinct values")
    print(f"names differing only by case: {len(dup)} groups")

    with open(args.out, "w", encoding="utf-8") as out:
        out.write(HEADER)
        for name in ordered:
            out.write(f"pub const KEY_{name}: u32 = {table[name]:#x};\n")
        out.write(
            "\n/// Every keysym name with its value, in libxkbcommon's `name_to_keysym`\n"
            "/// order: by ASCII case-folded name, then by name.\n"
        )
        out.write(
            f"pub(in crate::platform) static NAME_TO_KEYSYM: [(&str, u32); {len(ordered)}] = [\n"
        )
        for name in ordered:
            out.write(f'    ("{name}", KEY_{name}),\n')
        out.write("];\n")
    subprocess.run(["rustfmt", "--edition", "2024", args.out], check=True)


if __name__ == "__main__":
    main()
